    {
        switch ((code ?? "").Trim().ToLowerInvariant())
        {
            case "ko": case "kr": case "korean": return Lang.Ko;
            case "ja": case "jp": case "japanese": return Lang.Ja;
            case "en": case "english": return Lang.En;
            default: return Lang.Zh;
        }
    }

    public static string CodeOf(Lang lang) => lang switch
    {
        Lang.Ko => "ko",
        Lang.Ja => "ja",
        Lang.En => "en",
        _ => "zh",
    };

